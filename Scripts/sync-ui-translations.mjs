import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Generate the native lookup from the same reviewed dictionaries as the website.
const root = new URL('../', import.meta.url);
const load = locale => JSON.parse(readFileSync(new URL(`webApp/src/foodrun/${locale}.json`, root), 'utf8'));
const neutral = { ...load('ar'), ...load('ar-001') };
const dictionaries = { standard: neutral, egyptian: { ...neutral, ...load('ar-EG') }, emirati: { ...neutral, ...load('ar-AE') }, sudanese: { ...neutral, ...load('ar-SD') } };
const literal = value => JSON.stringify(value).replaceAll('$', '\\$');
const content = `// Generated by Scripts/sync-ui-translations.mjs. Edit the web Arabic dictionaries instead.
package com.karim.foodrun.shared.orders

internal object GroupUiText {
    fun translate(value: String, arabic: Boolean): String = translate(value, if(arabic) "ar-EG" else "en")
    fun translate(value: String, language: String): String {
        if(!language.startsWith("ar")) return value
        val translations = when(language) { "ar-SD" -> sudanese; "ar-AE" -> emirati; "ar-001" -> standard; else -> egyptian }
        return translations[value] ?: value
    }
${Object.entries(dictionaries).map(([name, values]) => `    private val ${name} by lazy { mapOf(\n${Object.entries(values).sort(([a],[b])=>a.localeCompare(b)).map(([en, ar]) => `        ${literal(en)} to ${literal(ar)},`).join('\n')}\n    ) }`).join('\n')}
}
`;
const target = new URL('shared/src/commonMain/kotlin/com/karim/foodrun/shared/orders/GroupUiText.kt', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== content) throw Error('Run node Scripts/sync-ui-translations.mjs to sync native translations.');
} else writeFileSync(target, content);
console.log(`Four shared Arabic dictionaries ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${fileURLToPath(target)}`);
