import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Generate the native lookup from the same reviewed dictionaries as the website.
const root = new URL('../', import.meta.url);
const entries = Object.entries({
  ...JSON.parse(readFileSync(new URL('webApp/src/foodrun/ar.json', root), 'utf8')),
  ...JSON.parse(readFileSync(new URL('webApp/src/foodrun/ar-EG.json', root), 'utf8')),
}).sort(([a], [b]) => a.localeCompare(b));
const literal = value => JSON.stringify(value).replaceAll('$', '\\$');
const content = `// Generated by Scripts/sync-ui-translations.mjs. Edit ar.json / ar-EG.json instead.
package com.karim.foodrun.shared.orders

internal object GroupUiText {
    fun translate(value: String, arabic: Boolean): String = if (arabic) translations[value] ?: value else value
    private val translations = mapOf(
${entries.map(([en, ar]) => `        ${literal(en)} to ${literal(ar)},`).join('\n')}
    )
}
`;
const target = new URL('shared/src/commonMain/kotlin/com/karim/foodrun/shared/orders/GroupUiText.kt', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== content) throw Error('Run node Scripts/sync-ui-translations.mjs to sync native translations.');
} else writeFileSync(target, content);
console.log(`${entries.length} shared Arabic translations ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${fileURLToPath(target)}`);
